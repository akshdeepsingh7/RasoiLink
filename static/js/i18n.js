// State manager
let currentLanguage = localStorage.getItem('rasoilink_lang') || 'en';

function getTranslation(key, fallback = '') {
  const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['en'];
  return langDict[key] || TRANSLATIONS['en'][key] || fallback || key;
}

function setLanguage(langCode) {
  if (!BHARAT_LANGUAGES[langCode]) {
    langCode = 'en';
  }
  currentLanguage = langCode;
  localStorage.setItem('rasoilink_lang', langCode);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langCode } }));
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const trans = getTranslation(key);
    if (trans) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = trans;
      } else if (el.querySelector('i, svg')) {
        // Preserve child icon/svg tags by only replacing the primary text node
        let textNode = null;
        for (let node of el.childNodes) {
          if (node.nodeType === Node.TEXT_NODE && node.nodeValue.trim().length > 0) {
            textNode = node;
            break;
          }
        }
        if (textNode) {
          textNode.nodeValue = ` ${trans} `;
        } else {
          el.insertAdjacentText('beforeend', ` ${trans}`);
        }
      } else {
        el.textContent = trans;
      }
    }
  });

  // Update language select if present
  const langBtnLabel = document.getElementById('currentLangLabel');
  if (langBtnLabel && BHARAT_LANGUAGES[currentLanguage]) {
    langBtnLabel.textContent = BHARAT_LANGUAGES[currentLanguage].native;
  }
}

// Global hook
window.t = getTranslation;
window.setLanguage = setLanguage;
window.getCurrentLanguage = () => currentLanguage;
window.BHARAT_LANGUAGES = BHARAT_LANGUAGES;

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
